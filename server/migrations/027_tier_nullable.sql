-- 027：prizes.tier 改成可以是 null —— 賞別是池的概念，不是卡的屬性
--
-- ── 為什麼 ──────────────────────────────────────────────────────────
-- 「A 賞」「B 賞」是**某一個池**對它的獎品做的分級：同一張噴火龍在
-- 這個池可以是 A 賞、在下一個池可以是 LAST 賞。賞別描述的是
-- 「這張卡在那個池裡的位置」，不是卡本身的性質。
--
-- 002_core.sql 把 tier 設成 NOT NULL，在當時是對的 —— 那時 prizes 只有
-- 一個入口（抽卡），每一列生下來就屬於某個池，賞別必然存在。
-- 卡冊優先（docs/inventory-first-plan.md）之後多了第二個入口：
-- 使用者把手上的實體卡直接登記進卡冊（routes/cardbook.ts 的上傳）。
-- 那張卡還沒進過任何池，賞別根本**還沒有發生**，強迫填一個值只有兩種
-- 下場：捏造一個假賞別（卡冊統計跟著失真），或塞哨兵字串（'NONE' 之類，
-- 每個讀的地方都要記得跳過它 —— 那就是用字串假扮 null）。
--
-- null 在這裡是誠實的值：「這張卡還沒進過池」。
-- 進池的那一刻（routes/pools.ts 建池押記的重用分支）會把賞別寫上。
--
-- ── 跑完之後行為不變 ────────────────────────────────────────────────
-- 既有的列一列都沒動（沒有任何 UPDATE）；既有的寫入路徑
-- （抽卡、建池押記、seed）全部都帶著 tier 值，不會突然開始寫 null。
-- 第一列 tier 為 null 的資料要等上傳端點上線才會出現。
--
-- ── 可逆性 ──────────────────────────────────────────────────────────
-- 完整退版（無損）：
--     alter table prizes alter column tier set not null;
-- ⚠️ 只有在**沒有任何 tier 為 null 的列**時做得到 —— 也就是退版窗口
--    只到第一張卡被上傳進卡冊為止。之後要退就得先處理那些列
--    （刪掉或補值），跟 021 的 pool_id 同一種限制，要寫進 runbook。

alter table prizes alter column tier drop not null;

comment on column prizes.tier is
  '這張卡在它的池裡的賞別（A/B/C/D/LAST/BUST）。'
  'null = 還沒進過任何池的卡（使用者上傳進卡冊的，見 origin=''upload''）。'
  '進池時（routes/pools.ts 建池押記）會被寫上；賞別是池的概念，'
  '不是卡的屬性 —— 同一張卡在不同的池可以是不同的賞。'
  '統計賞別分佈時 null 不計入（routes/prizes.ts 的 /summary）。';
