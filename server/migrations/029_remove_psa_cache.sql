-- 029：移除不可用的 PSA API 查證快取。
-- 鑑定公司、等級與編號仍保存在 cards/prizes 中，並繼續參與唯一性約束；
-- 只刪除外部 API 曾成功回傳的快取資料，平台不再宣稱或顯示 PSA 已查證。
--
-- ── 可逆性 ──────────────────────────────────────────────────────────
-- **這一支不是無損的，而且退不回原狀。** 上面三支（021/025/026）的退版
-- 都只是把結構改回去，資料還在；這一支 drop 的是資料本身。
--
-- 結構退版（照 020 的定義重建空表）：
--     重跑 migrations/020_psa_cert_cache.sql 的 create table。
--     它是 `create table if not exists`，在已經 drop 的庫上會照建。
--     ⚠️ 但 schema_migrations 裡 020 已記為套用過，migrate 不會再跑它 ——
--        要手動執行那段 DDL，或先從 schema_migrations 刪掉 020 那一列。
--
-- **資料退版：做不到。** psa_certs 的每一列都是某一次外部 API 呼叫的結果，
-- 而那個來源已經不可用（帳號待核准全 403），也就是說**重建不出來**。
--
-- 其中損失最大的是 `raw` 欄位。020:42-44 明講它的用途是
-- 「稽核『當初 PSA 到底回了什麼』的憑據」—— 這支把它一起刪了。
-- 代價要說清楚：
--   · 過去曾被標成 verified 的卡，**再也拿不出當初據以標記的原始回應**。
--     日後有人爭執「當時系統憑什麼說它 verified」，我們沒有東西可以出示。
--   · 那份資料同時是唯一的重查依據（checked_at）。刪掉之後，
--     連「這個編號上次是什麼時候查的」都不存在了。
--
-- 因此：**要保留稽核軌跡的環境，drop 之前必須先自己備份一份**，
--     create table psa_certs_archive as select * from psa_certs;
-- 這支刻意不自動建那張備份表 —— 它含外部授權資料，該不該留、留多久，
-- 是營運決定，不該由一支遷移替所有環境決定。
--
-- 退版窗口：drop 執行的那一刻就關上了。沒有備份就沒有回頭路。

drop table if exists psa_certs;