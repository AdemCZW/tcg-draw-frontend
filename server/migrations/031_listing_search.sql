-- 031: 市場搜尋。
--
-- ── 為什麼搜尋一定要在資料庫這一層 ──
--
-- 市場是游標分頁的（見 013 與 server/src/pagination.ts）。前端做過濾只濾得到
-- 「已經載進來的那一批」—— 使用者搜「伊布」看到 2 筆，而市場上其實有 15 筆，
-- 另外 13 筆躺在第 2、3 批。對排序來說那只是順序怪；對搜尋來說那是**錯的答案**，
-- 而且錯得看不出來（畫面上就是「只有 2 筆」）。卡冊的狀態過濾踩過同一個坑。
--
-- ── 為什麼要一個實體欄位，不是每次查詢現算 ──
--
-- 卡片資料在 card jsonb 裡，比對要先做三件事：Unicode 正規化、轉小寫、去空白。
-- 寫在 where 裡的話每一列每一次查詢都要重算一遍；更糟的是那條規則會散落在
-- 查詢字串與（未來的）索引定義兩個地方，只要有一邊改了就永遠對不上。
-- 存成 generated column 之後規則只有這裡這一份，查詢端只是拿它跟關鍵字比對。
--
-- 用 stored generated column 而不是觸發器：它由 Postgres 自己維護，
-- 不可能出現「有人繞過觸發器直接 update card」造成索引與資料不一致。
--
-- ── 正規化做了什麼、為什麼 ──
--
-- normalize(..., NFKC)
--   站上的卡名中文日文混雜，而且真的有全形字：種子資料裡就有「謎擬Ｑ」
--   （全形 Ｑ，U+FF31）。使用者打的是半形 Q，不正規化就搜不到自己看得見的卡。
--   NFKC 同時處理半形片假名（ﾘｻﾞｰﾄﾞﾝ → リザードン）、全形英數（ｅｘ → ex）、
--   以及全形空白 U+3000 與 NBSP → 一般空白（下一步才吃得掉）。
--
-- lower()
--   卡號與系列代碼是英數：使用者打 SV4A 跟 sv4a 想找的是同一件事。
--
-- regexp_replace(..., '\s+', '', 'g')
--   「噴火龍 ex SAR」與「噴火龍ex」在使用者眼裡是同一張卡。空白在中日文卡名裡
--   純粹是排版，不是語意的一部分，兩邊都拿掉最不會出人意料。
--   NFKC 已經把各種奇怪的空白收斂成一般空白，所以這一步吃得乾淨。
--
-- 沒有做的：平假名/片假名互換。「りざーどん」找「リザードン」在理論上可行，
-- 但輸入法在送出前就已經轉成片假名了，為了一個實際上不會發生的情境
-- 去攪動比對規則不划算。真的需要時再加，這一欄本來就是可以重算的。
--
-- ── 為什麼是這三個欄位 ──
--
-- name    使用者要找的東西本身。
-- setCode 順便讓「打 sv8a 就看到整個系列」成立 —— 使用者要的「依系列篩選」
--         不必再開一個下拉選單（真正想收的「伊布家族」本來就跨好幾個 setCode，
--         那是搜尋解得了、系列篩選解不了的需求）。
-- cardNo  使用者可能直接把卡號貼進來。
--
-- 沒有放 grader / grade：「10」會打中每一張 PSA 10 也會打中卡號裡的 10，
-- 噪音大於價值。沒有放 certNo：那是身分憑據，不對外（見 card-public.ts）。
--
-- 欄位之間用 '|' 隔開而不是空白 —— 空白會被上面那一步吃掉，
-- 三個欄位黏在一起會生出「跨欄位」的假命中（卡名結尾＋系列開頭）。
alter table listings add column if not exists search_text text
  generated always as (
    regexp_replace(lower(normalize(
      coalesce(card->>'name', '') || '|' ||
      coalesce(card->>'setCode', '') || '|' ||
      coalesce(card->>'cardNo', '')
    , NFKC)), '\s+', '', 'g')
  ) stored;

-- ── 為什麼這裡沒有建索引 ──
--
-- 比對用的是 strpos()（子字串位置），不是 LIKE，所以沒有任何 B-tree 用得上；
-- 唯一能加速子字串比對的是 pg_trgm 的 GIN 索引，而它對這個站的主要查詢
-- **幫不上忙**：實測 50,000 筆掛單（43,000 筆 live），
--   like '%月亮伊布%'（4 字）→ 走得到 trigram 索引，1.4 ms
--   like '%伊布%'   （2 字）→ 規劃器根本不採用，退回過濾，3.9 ms
-- 兩個字的中文關鍵字切不出一個完整的三連字，這是 pg_trgm 的先天限制，
-- 而「打伊布找伊布家族」正是這個功能存在的理由。
--
-- 同一份資料量下，現在這條路（部分掃描 live 掛單 + strpos）最壞情況
-- （完全沒有命中、要掃完全部）是 3.0 ms。掛單是會賣掉會下架的，
-- live 的數量不像卡冊那樣只增不減。
--
-- 成長之後怎麼辦，照這個順序：
--   1. 先量。live 掛單到六位數之前不需要動任何東西。
--   2. 真的慢了，第一步是 partial index on (status) 之外把搜尋改成
--      LIKE + pg_trgm GIN（對 3 字以上的關鍵字立刻有效），
--      並且接受 2 字關鍵字仍然要掃。
--   3. 2 字中文關鍵字要走索引，只有換一套斷詞/n-gram 的方案
--      （pgroonga、或自己維護一張 2-gram 反向索引表）。那是另一個決定，
--      不要在資料量還沒到之前先付它的維護成本。
