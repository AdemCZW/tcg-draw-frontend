-- 025：系統自我檢測的狀態表
--
-- ── 為什麼需要 ──────────────────────────────────────────────────────
-- 自我檢測（server/src/monitor.ts）的第一條不變式是「帳本總量 = 發行量」。
-- 但有舊資料的環境（正式環境就是）drift 停在一個**已知的非零常數**：
-- 017 之前的抽卡票金真的被銷毀了，刻意不回填（回填等於現在才印鈔票，
-- 見 017 的說明）。所以「drift ≠ 0」在那些環境不是異常。
--
-- 真正的異常訊號是 **drift 變了**：常數會一直是同一個常數，
-- 一旦動了就代表有一筆分錄只寫了單邊 —— 那才要拉警報。
-- 要偵測「變了」就得記得上一次看到的值，這張表就是為了這一件事。
--
-- 只開一張通用的 key/value 表而不是替每個檢查開欄位：
-- 之後別的檢查也可能需要基準值，不要每加一個就跑一次遷移。
--
-- ── 可逆性 ──────────────────────────────────────────────────────────
-- 完整退版（無損）：drop table if exists monitor_state;
-- 既有的表一列都沒被動過。

create table if not exists monitor_state (
  key        text primary key,
  value      text not null,
  updated_at bigint not null
);

comment on table monitor_state is
  '自我檢測的基準值（server/src/monitor.ts）。'
  '目前只有 ledger-drift 的上次觀測值。這張表**不是**任何業務事實的來源，'
  '整張刪掉只會讓下一次檢測把當下的 drift 重新當成基準。';
