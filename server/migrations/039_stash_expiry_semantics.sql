-- 039：把 stash_expires_at 的語意寫進資料庫（D-2 的結論，沒有 schema 變更）
--
-- ── 為什麼要有這一支 ────────────────────────────────────────────────
-- docs/open-issues.md 的 D-2 說「過戶時不重設 stash_expires_at，看起來是
-- 漏掉的」。重查的結論是**相反的**：不重設是對的，而且重設會是一個 bug。
-- 這支遷移不改任何資料，只是把那個結論留在 schema 裡 —— 因為下一個
-- 讀到「三條過戶路都更新了 acquired_at、都沒碰 stash_expires_at」的人
-- 會得出跟 D-2 一樣的直覺，然後把它「修好」。
--
-- ── 那 90 天量的是什麼 ──────────────────────────────────────────────
-- 不是「你擁有這張卡多久了」，是「這張**實體卡**在別人的抽屜裡放了多久」。
-- 平台不代管實體卡（HANDOFF.md 4.2）：抽中之後卡還在開池的賣家那裡，
-- 而他的票金 14 天就結清入袋了，保管義務卻沒有終點。stash_expires_at
-- 就是那個義務的計時器，pools-service.ts 的 sweepStashExpiry 靠它提醒。
--
-- 承接這件事的欄位是 custodian_id（見 021 的說明）：站內交易一律不碰它。
-- 所以庫內轉移與交易邀約成交時，實體卡一步都沒有動 —— 時鐘沒有理由歸零。
-- 而實體真的會動的那兩條路（出貨簽收、站外轉手接管）都會把 status 改成
-- 'shipped' / 'in_book'，掃描只看 'stashed'，那個欄位從此不再被讀。
--
-- ── 重設還會開一個免費的洞 ──────────────────────────────────────────
-- 庫內轉移雙方帳目相抵、沒有手續費，交易邀約也一樣。重設成 90 天的話，
-- 一個人用兩個帳號互相買賣同一張卡就能把時鐘無限往後推，而那則
-- 「這張卡放很久了」的提醒 —— 唯一保護實體保管人的機制 —— 永遠不會發。
--
-- ── 還沒拍板的部分 ──────────────────────────────────────────────────
-- 「到期之後要做什麼」仍然是政策問題（DESIGN.md 第 9 節），目前只通知、
-- 不扣卡、不強制出貨。這支遷移不預設任何答案。

