-- 012：把還元率存進池
--
-- 還元率（獎品總值 ÷ 票收）原本只在前端算來顯示給賣家看，資料庫裡沒有這個數字。
-- 兩個後果：
--   1. 護欄只在瀏覽器裡 —— 賣家直接打 API 就能開一個還元率 20% 的池
--   2. 買家看不到這個數字。那是判斷一個池值不值得抽最直接的依據，
--      而同業幾乎沒有人公開它
--
-- 存下來的是**開賣當下**算的值。之後 refPrice 就算變動也不改這個數字：
-- 它是承諾的一部分，事後浮動的行情不該回頭改寫當初宣告的條件。

alter table pools add column if not exists return_ratio numeric(6,2);
