/**
 * 示範池 id 的世代字尾。
 *
 * seedPool 看到 id 已存在就整個跳過（那是對的 —— 重跑種子不該把別人抽到
 * 一半的池洗掉）。但也因此，種子的規則改了之後，**既有環境上的舊池永遠
 * 不會被更新**。正式環境就出現過這個後果：買回價上線之後，線上 16 個池
 * 全部沒有買回價，抽到的卡一張都回收不了。
 *
 * 換世代字尾等於「開一批新的池」，舊的原封不動留著（seed 的 retireStalePools
 * 會把它們關掉）。這比刪除安全 —— prizes.pool_id 是 not null 外鍵，
 * 刪池等於毀掉別人卡冊裡已經抽到的卡。
 *
 * 放在獨立的檔案是因為煙霧測試也要用同一個值。直接 import seed.ts 會
 * 執行整支種子腳本，所以只把常數抽出來。
 */
export const GEN = '-g2'

/** 把示範池的基礎 id 加上目前的世代字尾 */
export const genId = (id: string) => `${id}${GEN}`
