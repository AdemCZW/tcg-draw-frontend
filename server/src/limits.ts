/**
 * 使用者輸入的金額上界。
 *
 * ── 這裡的數字是「荒謬值防線」，不是價值上限、更不是定價政策 ──
 *
 * 沒有上界的金額欄位會直接變成 500：`z.number().int().positive()` 收得下
 * `1e308`（JS 眼裡它是整數），那個值進到 bigint 欄位時 Postgres 會回
 * 22P02 / pg_strtoint64_safe，Hono 就回一句 `Internal Server Error`。
 * 也就是說**使用者的輸入錯誤被講成伺服器故障** —— 他不知道自己打錯了，
 * 我們的錯誤率圖表也被自己的使用者打錯字污染。這是唯一要解的問題。
 *
 * 所以取值的原則只有一條：**任何真人可能真的想輸入的數字都必須通過。**
 * 卡片大獎的價值可以非常高 —— 目前世界紀錄的單張卡成交價約 530 萬美元
 * （約新台幣 1.7 億）。上界必須遠高於那個數字，否則我們擋掉的不是手滑，
 * 是一筆真實交易，而那比 500 嚴重得多。
 *
 * 同一個哲學在 shared/pool-settlement.ts 的 BUYBACK_MAX（一千萬點）
 * 就寫過了：「這是一個荒謬值防線，不是經濟門檻……擋的是手滑多打幾個零」。
 * 真正的經濟門檻在別的地方（整池的 Σ 買回價要低於票收，見 shared/economics.ts），
 * 不在單一欄位的 `.max()` 上。
 */

/**
 * 使用者自己輸入的點數金額上界：**十億點**。
 *
 * 為什麼是十億而不是別的數字：
 *
 *   上緣 —— 它必須高到擋不到任何真的交易。十億點（約合三千萬美元）是
 *   史上最貴單張卡成交價的六倍左右。要打到這個數字，一張卡得比人類賣過的
 *   任何一張卡貴上五倍以上；那不是高價交易，那是多打了好幾個零。
 *
 *   下緣 —— 它必須低到不可能溢位。bigint 的極限是 9.22e18，
 *   十億離它還有九個數量級；十億也遠在 JS 的 Number.MAX_SAFE_INTEGER
 *   （9.01e15）之下，所以這個值在前後端之間傳遞時不會失去精度。
 *
 * 刻意比同一個 repo 裡既有的 `.max(100_000_000)`（admin 發點數、
 * 交易出價）**寬一個數量級**。那兩個管的是「平台憑空發行多少點」與
 * 「站內出價」，收緊有其道理；這一個管的是「一張卡賣多少錢」，
 * 而卡的價格上限是市場決定的，不該由我們的驗證碼決定。
 */
export const POINTS_INPUT_MAX = 1_000_000_000

/** 給錯誤訊息用的中文寫法，避免每個呼叫端各自 toLocaleString 出不同格式 */
export const pointsInputMaxText = () => POINTS_INPUT_MAX.toLocaleString('zh-TW')
