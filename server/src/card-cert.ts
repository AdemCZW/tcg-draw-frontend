/**
 * 卡片身分驗證的共用件。
 *
 * 原本住在 routes/pools.ts（建池是當時唯一會驗鑑定編號的地方）。
 * 卡冊上傳（routes/cardbook.ts）要走**同一套**對照與上限 —— 兩邊各寫
 * 一份的話，規則遲早分岔：一邊修了對照邏輯另一邊沒跟上，同一個編號
 * 在上傳時被放行、在建池時被擋（或反過來），使用者看到的就是隨機。
 * 所以搬到這裡讓兩邊 import 同一份。
 */

/**
 * 一個卡號拆成「卡面編號」與「該套總數」。
 *
 * 卡面印的是 `編號/總數`（`331/190` ＝ 這一套的第 331 張，全套 190 張）。
 * 那是**兩個不同的事實**，斜線是它們的分隔符，不是編號的一部分。
 * 把整串當一個數字看（舊版就是這樣做的：把所有數字接起來變成 "331190"）
 * 等於發明了一個世界上不存在的編號。
 *
 * 正規化只做三件不會改變意義的事：
 *   - 大寫（`sv4a` 與 `SV4A` 是同一套）
 *   - 去掉非英數字（空白、破折號、井號都只是寫法）
 *   - 每一段數字去前導零（PSA 常寫 `025`，卡面印 `25`）
 */
function splitCardNo(s: string): { local: string; total: string | null } {
  const norm = (x: string) =>
    x.toUpperCase().replace(/[^A-Z0-9]/g, '').replace(/\d+/g, d => d.replace(/^0+(?=\d)/, ''))
  const i = s.indexOf('/')
  return i < 0
    ? { local: norm(s), total: null }
    : { local: norm(s.slice(0, i)), total: norm(s.slice(i + 1)) || null }
}

/**
 * PSA 回的卡號跟賣家挑的卡號對不對得上。
 *
 * 為什麼不是字串相等：PSA 是英文、我們的目錄是日文，**卡名**不可能字串相等，
 * 所以對照只能靠卡號。而兩邊的寫法本來就不一致 ——
 * **PSA 的 CardNumber 對日版卡通常是裸的流水號（`331`），我們的目錄用的是
 * 卡面印的 `編號/總數`（`331/190`）。**
 *
 * ── 這裡修過一次，修的是什麼 ────────────────────────────────────────
 * 舊版把兩邊的數字全部串起來比：
 *     digits("331") = "331"   digits("331/190") = "331190"   → 判成不同的卡
 * 於是**每一張日版鑑定卡都會撞上 CERT_MISMATCH**。那不是例外，是常態：
 * 只要 PSA 不附總數（而它通常不附），這條路就一定要使用者手動確認一次。
 * 一個「幾乎每次都會跳」的確認框等於沒有確認框 —— 使用者會學會閉著眼睛勾，
 * 而它本來要攔的那種「真的挑錯卡」就跟著被勾過去了。
 *
 * 現在比的是**分開的兩段**：
 *   - 卡面編號一定要相等（`331` vs `331` ✔；`331` vs `332` ✘）
 *   - 總數**只有兩邊都寫了才比**（`331/190` vs `331/191` ✘）。
 *     只有一邊有的時候，缺的那一邊是「沒寫」不是「不一樣」——
 *     拿沒寫當成矛盾，就是舊版那個 bug 換一個寫法。
 *
 * ── 刻意**不**處理的一種 ────────────────────────────────────────────
 * 一邊帶系列前綴、另一邊沒有（PSA `SV4A-331` vs 目錄 `331/190`）仍然判成
 * 對不上。要放行它就得猜「哪一段是前綴」，而 `1331` 與 `331` 的尾碼也相同 ——
 * 猜錯的代價是把兩張不同的卡判成同一張，那正是這個函式唯一要擋的事。
 * 這一種交給使用者確認：他看得到 PSA 查到的卡號，比程式猜得準。
 *
 * **比不出來就回 true（不擋）**：這個函式只負責抓「明顯是另一張卡」，
 * 拿不準的一律放行、交給賣家自己看 PSA 的卡片資訊確認 —— 寧可多問一次，
 * 也不要把一張其實對得上的卡誤擋成假卡。
 */
export function cardNumbersAgree(psa: string | null, seller: string | null): boolean {
  if (!psa || !seller) return true
  const a = splitCardNo(psa), b = splitCardNo(seller)
  /* 任一邊連一個英數字都湊不出來（例如 PSA 回空字串或純符號）：
     沒有東西可以比，退回整串比對，比不出結論就放行。 */
  if (!a.local || !b.local) {
    const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, '')
    return norm(psa) === norm(seller)
  }
  if (a.local !== b.local) return false
  if (a.total && b.total && a.total !== b.total) return false
  return true
}

